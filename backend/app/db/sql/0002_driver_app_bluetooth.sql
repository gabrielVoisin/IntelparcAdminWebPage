-- =====================================================================
-- Parking management platform - schema v2
-- Driver app (Intel Park) + Bluetooth identification at the bay
--
-- * customers can sign in to the Android app (scrypt password, own refresh tokens)
-- * phone numbers are verified with an SMS code
-- * a parking session records WHO is parked and HOW it was recognised:
--     bluetooth (phone identified by the cabinet), camera (plate read), app (QR code + payment), manual
-- * every Bluetooth identification received by a cabinet is kept (ble_identifications)
-- * photos taken by agents before a fine are kept as evidence (alarm_evidence)
-- * new alarm reason: a reserved / assigned bay used by another user
-- =====================================================================

-- ---------------------------------------------------------------------
-- New enum values (must run outside a transaction block before use; the
-- migration runs them first, see alembic/versions/0002_driver_app.py)
-- ---------------------------------------------------------------------
-- ALTER TYPE alarm_reason ADD VALUE IF NOT EXISTS 'reserved_bay_misuse';   (executed separately)

CREATE TYPE identification_method AS ENUM ('bluetooth', 'camera', 'app', 'manual');
CREATE TYPE identification_status AS ENUM ('authorised', 'payment_required', 'reserved_by_other', 'wrong_bay', 'pending');

-- ---------------------------------------------------------------------
-- Customers: app accounts
-- ---------------------------------------------------------------------
ALTER TABLE customers
  ADD COLUMN password_hash      TEXT,                       -- NULL = no app account (created by staff)
  ADD COLUMN phone_verified_at  TIMESTAMPTZ,
  ADD COLUMN last_login_at      TIMESTAMPTZ;

-- One app account per e-mail (customers created by staff without an account are not concerned)
CREATE UNIQUE INDEX customers_app_email_uq ON customers (lower(email)) WHERE password_hash IS NOT NULL;

-- Customer references "C-10000", "C-10001"... for self-registered drivers
CREATE SEQUENCE customer_reference_seq START 10000;

CREATE TABLE customer_refresh_tokens (
  id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  customer_id   UUID NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
  token_hash    TEXT NOT NULL UNIQUE,                       -- SHA-256 of the token, never the token
  client_name   TEXT,                                       -- "Android · Pixel 8"
  expires_at    TIMESTAMPTZ NOT NULL,
  revoked_at    TIMESTAMPTZ,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX customer_refresh_tokens_customer_idx ON customer_refresh_tokens (customer_id);

-- SMS verification codes (only the hash is stored, 10 minutes, 5 attempts)
CREATE TABLE customer_phone_codes (
  id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  customer_id   UUID NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
  phone         TEXT NOT NULL,                              -- E.164
  code_hash     TEXT NOT NULL,
  attempts      SMALLINT NOT NULL DEFAULT 0,
  expires_at    TIMESTAMPTZ NOT NULL,
  used_at       TIMESTAMPTZ,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX customer_phone_codes_customer_idx ON customer_phone_codes (customer_id, created_at DESC);

-- ---------------------------------------------------------------------
-- Parking sessions: who is parked, and how they were recognised
-- ---------------------------------------------------------------------
ALTER TABLE parking_sessions
  ADD COLUMN customer_id     UUID REFERENCES customers(id) ON DELETE SET NULL,
  ADD COLUMN identified_by   identification_method,
  ADD COLUMN identified_at   TIMESTAMPTZ;
CREATE INDEX parking_sessions_customer_idx ON parking_sessions (customer_id, entered_at DESC);

-- Payments made in the app may come from a customer without a vehicle on file
ALTER TABLE payments ADD COLUMN provider TEXT;              -- "demo", "stripe", "twint"...

-- ---------------------------------------------------------------------
-- Bluetooth identifications received by the cabinets
-- ---------------------------------------------------------------------
CREATE TABLE ble_identifications (
  id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  controller_id   UUID NOT NULL REFERENCES controllers(id) ON DELETE CASCADE,
  identification_uid TEXT NOT NULL,                         -- generated by the Pi: idempotent upload
  customer_id     UUID NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
  vehicle_id      UUID REFERENCES vehicles(id) ON DELETE SET NULL,
  bay_id          UUID REFERENCES bays(id) ON DELETE SET NULL,   -- bay given by the phone, or matched later
  rssi            SMALLINT,                                 -- signal strength measured by the phone (dBm)
  identified_at   TIMESTAMPTZ NOT NULL,                     -- when the cabinet verified the phone
  received_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  session_id      UUID REFERENCES parking_sessions(id) ON DELETE SET NULL,
  status          identification_status NOT NULL DEFAULT 'pending',
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (controller_id, identification_uid)
);
CREATE INDEX ble_identifications_pending_idx ON ble_identifications (controller_id, identified_at DESC) WHERE session_id IS NULL;
CREATE INDEX ble_identifications_customer_idx ON ble_identifications (customer_id, identified_at DESC);

-- ---------------------------------------------------------------------
-- Evidence photos taken by agents (plate) before a fine
-- ---------------------------------------------------------------------
CREATE TABLE alarm_evidence (
  id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  alarm_id      UUID NOT NULL REFERENCES payment_alarms(id) ON DELETE CASCADE,
  file_name     TEXT NOT NULL,                              -- stored under EVIDENCE_DIR
  content_type  TEXT NOT NULL DEFAULT 'image/jpeg',
  size_bytes    INTEGER NOT NULL,
  sha256        TEXT NOT NULL,
  plate_read    TEXT,                                       -- plate read on the phone (OCR), as typed
  taken_by      UUID REFERENCES staff_users(id) ON DELETE SET NULL,
  taken_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX alarm_evidence_alarm_idx ON alarm_evidence (alarm_id);

-- ---------------------------------------------------------------------
-- Audit log: customers act too (registration, payments, bookings)
-- ---------------------------------------------------------------------
ALTER TABLE audit_log DROP CONSTRAINT IF EXISTS audit_log_actor_kind_check;
ALTER TABLE audit_log ADD CONSTRAINT audit_log_actor_kind_check CHECK (actor_kind IN ('staff', 'controller', 'system', 'customer'));

-- updated_at triggers for the new tables
CREATE TRIGGER customer_refresh_tokens_updated_at BEFORE UPDATE ON customer_refresh_tokens FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER customer_phone_codes_updated_at BEFORE UPDATE ON customer_phone_codes FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER ble_identifications_updated_at BEFORE UPDATE ON ble_identifications FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER alarm_evidence_updated_at BEFORE UPDATE ON alarm_evidence FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------------
-- What a customer is entitled to on a bay right now (used by the
-- Bluetooth decision, the app home screen and the alarm engine)
-- ---------------------------------------------------------------------
CREATE VIEW v_customer_rights AS
SELECT s.customer_id, s.site_id, s.bay_id, 'subscription'::text AS kind, s.id AS ref_id,
       NULL::timestamptz AS valid_until
FROM subscriptions s
WHERE s.status = 'active' AND NOT s.payment_overdue AND current_date BETWEEN s.starts_on AND s.ends_on
UNION ALL
SELECT r.customer_id, z.site_id, r.bay_id, 'reservation', r.id, r.ends_at
FROM reservations r JOIN bays b ON b.id = r.bay_id JOIN zones z ON z.id = b.zone_id
WHERE r.status IN ('confirmed', 'active') AND r.starts_at <= now() + interval '30 minutes' AND r.ends_at > now()
UNION ALL
SELECT p.customer_id, p.site_id, p.bay_id, 'paid_session', p.id, p.paid_until
FROM parking_sessions p
WHERE p.status = 'open' AND p.customer_id IS NOT NULL AND p.paid_until > now();
